// The testable core of the iOS device end, and why the tools version owns the first line: SwiftPM
// reads it there before anything else, so the licence notice sits below it rather than above.
//
// Three libraries of pure logic — the wire format, the H.264 container work, and the Foundation-only
// DeviceCoordinator state machine — plus tests that assert them against byte fixtures and fake pictures.
//
//   cd device-ios && swift test
//
// The platform-dependent code (ReplayKit capture, VideoToolbox, the socket against a running relay)
// is in ../App, built by the Xcode project generated from project.yml. It is left out of this
// package on purpose: a test suite that cannot run on the machine it is written on is a suite that
// never ran.

import PackageDescription

let package = Package(
    name: "mirrorplay-device",
    platforms: [
        .iOS(.v16),
        .macOS(.v13), // the codec logic is platform-neutral, so it can be tested without a device
    ],
    products: [
        .library(name: "MirrorplayWire", targets: ["MirrorplayWire"]),
        .library(name: "MirrorplayH264", targets: ["MirrorplayH264"]),
        .library(name: "MirrorplayDeviceKit", targets: ["MirrorplayDeviceKit"]),
    ],
    targets: [
        .target(name: "MirrorplayWire"),
        .target(name: "MirrorplayH264"),
        .target(name: "MirrorplayDeviceKit"),
        .testTarget(
            name: "MirrorplayWireTests",
            dependencies: ["MirrorplayWire"],
            // The fixtures are generated by `node scripts/ios-fixtures.mjs` in the repository root.
            path: "Tests/MirrorplayWireTests"
        ),
        .testTarget(
            name: "MirrorplayH264Tests",
            dependencies: ["MirrorplayH264", "MirrorplayWire"],
            path: "Tests/MirrorplayH264Tests"
        ),
        .testTarget(
            name: "MirrorplayDeviceKitTests",
            dependencies: ["MirrorplayDeviceKit", "MirrorplayWire"],
            path: "Tests/MirrorplayDeviceKitTests"
        ),
    ]
)
