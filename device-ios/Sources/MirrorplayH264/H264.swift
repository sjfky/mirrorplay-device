// The H.264 records this input端 puts on the wire, and the container it has to produce.
//
// What a hardware encoder gives an app is one finished access unit per sample: the picture, with the
// sequence and picture parameter sets repeated in band on an IDR and nowhere else. The projection
// payload is those same units with four-byte big-endian lengths in place of start codes — AVCC —
// because that is what a receiver configures a decoder from, and it is one shape for every source
// (ffmpeg, a browser tab, an iPhone) instead of one per source.
//
// Mirrors `src/media/nal.js`, `src/media/avc.js` and `src/media/bits.js`. The byte-level agreement is
// asserted in FixtureTests.swift against files generated by those modules.

import Foundation

public enum H264Error: Error, CustomStringConvertible {
    case missingParameterSets
    case truncatedRecord
    case unsupportedAvcCVersion(UInt8)
    case invalidNalLengthSize(UInt8)
    case nalLengthTooLong(declared: Int, available: Int)
    case emptyNalUnit
    case unexpectedBytesBeforeStartCode
    case invalidPictureSize(width: Int, height: Int)
    case invalidSeqParameterSetId(Int)
    case invalidChromaFormat(Int)
    case unsupportedBitDepth
    case invalidFrameNum(Int)
    case invalidPicOrderCntType(Int)
    case pictureOrderCycleTooLong(Int)

    public var description: String {
        switch self {
        case .missingParameterSets: return "the access unit carries no SPS and PPS"
        case .truncatedRecord: return "the avcC record ends in the middle of a parameter set"
        case .unsupportedAvcCVersion(let v): return "unsupported avcC version \(v)"
        case .invalidNalLengthSize(let v): return "avcC NAL length size \(v) is reserved"
        case .nalLengthTooLong(let declared, let available): return "a NAL unit claims \(declared) bytes with \(available) left"
        case .emptyNalUnit: return "a NAL unit of zero length"
        case .unexpectedBytesBeforeStartCode: return "bytes before the first start code"
        case .invalidPictureSize(let w, let h): return "invalid picture size \(w)×\(h)"
        case .invalidSeqParameterSetId(let v): return "invalid seq_parameter_set_id \(v)"
        case .invalidChromaFormat(let v): return "invalid chroma_format_idc \(v)"
        case .unsupportedBitDepth: return "unsupported AVC bit depth"
        case .invalidFrameNum(let v): return "invalid log2_max_frame_num_minus4 \(v)"
        case .invalidPicOrderCntType(let v): return "invalid pic_order_cnt_type \(v)"
        case .pictureOrderCycleTooLong(let n): return "picture-order cycle of \(n)"
        }
    }
}

/// The profiles whose SPS carries the extra fields a reader has to step over.
private let highProfiles: Set<UInt8> = [44, 83, 86, 100, 110, 118, 122, 128, 134, 135, 138, 139, 144, 244]

/// One H.264 NAL unit's type, the low five bits of its first byte.
public func nalType(_ unit: Data) -> Int { Int(unit.first ?? 0) & 0x1f }

public func isKeyFrame(units: [Data]) -> Bool { units.contains { nalType($0) == 5 } }

/// Annex B (start codes) → the units inside it. Accepts three- and four-byte start codes and trims
/// the trailing zeros of the last unit, exactly as the JavaScript splitter does.
public func annexBUnits(_ data: Data) throws -> [Data] {
    let bytes = [UInt8](data)
    var units: [Data] = []
    var index = 0
    var zeros = 0
    var start = -1
    while index < bytes.count {
        if bytes[index] == 1 && zeros >= 2 {
            let prefix = index - zeros
            if start >= 0 {
                guard prefix > start else { throw H264Error.emptyNalUnit }
                units.append(Data(bytes[start..<prefix]))
            } else if prefix != 0 {
                throw H264Error.unexpectedBytesBeforeStartCode
            }
            start = index + 1
            zeros = 0
            index += 1
            continue
        }
        if start < 0 && bytes[index] != 0 { throw H264Error.unexpectedBytesBeforeStartCode }
        zeros = bytes[index] == 0 ? zeros + 1 : 0
        index += 1
    }
    guard start >= 0 else { throw H264Error.unexpectedBytesBeforeStartCode }
    let end = bytes.count - zeros
    guard end > start else { throw H264Error.emptyNalUnit }
    units.append(Data(bytes[start..<end]))
    return units
}

/// The units inside an AVCC access unit: four-byte length, then the NAL, repeated.
public func avccUnits(_ data: Data) throws -> [Data] {
    let bytes = [UInt8](data)
    var units: [Data] = []
    var index = 0
    while index < bytes.count {
        guard bytes.count - index >= 4 else { throw H264Error.nalLengthTooLong(declared: 0, available: bytes.count - index) }
        let length = Int(UInt32(bytes[index]) << 24 | UInt32(bytes[index + 1]) << 16 | UInt32(bytes[index + 2]) << 8 | UInt32(bytes[index + 3]))
        index += 4
        guard length > 0, length <= bytes.count - index else { throw H264Error.nalLengthTooLong(declared: length, available: bytes.count - index) }
        units.append(Data(bytes[index..<(index + length)]))
        index += length
    }
    return units
}

public func annexBToAvcc(_ data: Data) throws -> Data {
    var out = Data()
    for unit in try annexBUnits(data) {
        var length = UInt32(unit.count).bigEndian
        withUnsafeBytes(of: &length) { out.append(contentsOf: $0) }
        out.append(unit)
    }
    return out
}

public func avccToAnnexB(_ data: Data) throws -> Data {
    var out = Data()
    for unit in try avccUnits(data) {
        out.append(contentsOf: [0, 0, 0, 1])
        out.append(unit)
    }
    return out
}

/// Parameter sets pulled out of an access unit, in whichever container it arrives in.
public func parameterSets(accessUnit data: Data, annexB: Bool) throws -> (sps: Data, pps: Data) {
    let units = try annexB ? annexBUnits(data) : avccUnits(data)
    var sps: Data?
    var pps: Data?
    for unit in units {
        switch nalType(unit) {
        case 7: if sps == nil { sps = unit }
        case 8: if pps == nil { pps = unit }
        default: break
        }
    }
    guard let sequence = sps, let picture = pps else { throw H264Error.missingParameterSets }
    return (sequence, picture)
}

/// The decoder configuration record: what `video-format.format.config` carries, base64.
public struct AvcC {
    public let bytes: Data
    public let profile: UInt8
    public let compatibility: UInt8
    public let level: UInt8
    public let nalLengthSize: Int
    public let width: Int
    public let height: Int

    /// The string a WebCodecs `VideoDecoder` is configured with.
    public var codecString: String {
        String(format: "avc1.%02X%02X%02X", profile, compatibility, level)
    }

    public init(sps: Data, pps: Data) throws {
        guard sps.count >= 4 else { throw H264Error.missingParameterSets }
        var record = Data([1, sps[sps.startIndex + 1], sps[sps.startIndex + 2], sps[sps.startIndex + 3], 0xff, 0xe1])
        var spsLength = UInt16(sps.count).bigEndian
        withUnsafeBytes(of: &spsLength) { record.append(contentsOf: $0) }
        record.append(sps)
        record.append(1)
        var ppsLength = UInt16(pps.count).bigEndian
        withUnsafeBytes(of: &ppsLength) { record.append(contentsOf: $0) }
        record.append(pps)
        self.bytes = record
        self.profile = record[record.startIndex + 1]
        self.compatibility = record[record.startIndex + 2]
        self.level = record[record.startIndex + 3]
        self.nalLengthSize = 4
        let size = try SPS.dimensions(sps)
        self.width = size.width
        self.height = size.height
    }

    /// Read a record an encoder or a peer produced. The reserved bits are ignored, as FFmpeg and
    /// Chromium ignore them, so a record from an odd source does not become a decoding failure.
    public init(record: Data) throws {
        let bytes = [UInt8](record)
        guard bytes.count >= 6 else { throw H264Error.truncatedRecord }
        guard bytes[0] == 1 else { throw H264Error.unsupportedAvcCVersion(bytes[0]) }
        guard (bytes[4] & 0x03) != 2 else { throw H264Error.invalidNalLengthSize(bytes[4] & 0x03) }
        var index = 5
        let spsCount = Int(bytes[index] & 0x1f)
        index += 1
        var spsList: [Data] = []
        for _ in 0..<spsCount {
            guard bytes.count - index >= 2 else { throw H264Error.truncatedRecord }
            let length = Int(bytes[index]) << 8 | Int(bytes[index + 1])
            index += 2
            guard length > 0, length <= bytes.count - index else { throw H264Error.truncatedRecord }
            spsList.append(Data(bytes[index..<(index + length)]))
            index += length
        }
        guard index < bytes.count else { throw H264Error.truncatedRecord }
        let ppsCount = Int(bytes[index])
        index += 1
        var ppsList: [Data] = []
        for _ in 0..<ppsCount {
            guard bytes.count - index >= 2 else { throw H264Error.truncatedRecord }
            let length = Int(bytes[index]) << 8 | Int(bytes[index + 1])
            index += 2
            guard length > 0, length <= bytes.count - index else { throw H264Error.truncatedRecord }
            ppsList.append(Data(bytes[index..<(index + length)]))
            index += length
        }
        // The wire payload format is four-byte NAL lengths, full stop; a record offering anything
        // else is refused before a decoder is configured from it.
        guard Int(bytes[4] & 0x03) + 1 == 4 else { throw H264Error.invalidNalLengthSize(bytes[4] & 0x03) }
        guard let sps = spsList.first, let pps = ppsList.first, !sps.isEmpty, !pps.isEmpty else {
            throw H264Error.missingParameterSets
        }
        self.bytes = Data(record)
        self.profile = bytes[1]
        self.compatibility = bytes[2]
        self.level = bytes[3]
        self.nalLengthSize = 4
        let size = try SPS.dimensions(sps)
        self.width = size.width
        self.height = size.height
    }
}

/// Exp-Golomb reading over an SPS, with emulation prevention (00 00 03) already removed.
public struct BitReader {
    private let bits: [Bool]
    /// How far the walk has got. A reader that stops early is how a wrong picture size happens, so
    /// this is worth being able to look at.
    public private(set) var consumedBits = 0
    private var index = 0

    public init(_ data: Data, startingAt offset: Int = 0) {
        let bytes = [UInt8](data)
        var stripped: [UInt8] = []
        var i = min(max(offset, 0), bytes.count)
        let limit = bytes.count
        while i < limit {
            if i + 2 < limit && bytes[i] == 0 && bytes[i + 1] == 0 && bytes[i + 2] == 3 {
                stripped.append(0)
                stripped.append(0)
                i += 3
                continue
            }
            stripped.append(bytes[i])
            i += 1
        }
        var collected: [Bool] = []
        collected.reserveCapacity(stripped.count * 8)
        for byte in stripped {
            for shift in stride(from: 7, through: 0, by: -1) { collected.append((byte >> shift) & 1 == 1) }
        }
        self.bits = collected
    }

    public mutating func read(_ count: Int) -> Int {
        var value = 0
        for _ in 0..<count {
            let bit = index < bits.count && bits[index] ? 1 : 0
            value = (value << 1) | bit
            index += 1
            consumedBits += 1
        }
        return value
    }

    public mutating func flag() -> Bool { read(1) == 1 }

    public mutating func unsignedExpGolomb() throws -> Int {
        var zeros = 0
        while index < bits.count && !bits[index] {
            zeros += 1
            index += 1
            if zeros > 31 { throw H264Error.invalidSeqParameterSetId(zeros) }
        }
        index += 1 // the terminating one
        guard zeros > 0 else { return 0 }
        return (1 << zeros) - 1 + read(zeros)
    }

    public mutating func signedExpGolomb() throws -> Int {
        let code = try unsignedExpGolomb()
        return code & 1 == 1 ? (code + 1) >> 1 : -(code >> 1)
    }
}

public enum SPS {
    /// Width and height of a picture, honouring the chroma format, the frame-only flag and the
    /// cropping window — the three things that make "the size in the SPS" differ from the size of
    /// the coded surface.
    public static func dimensions(_ sps: Data) throws -> (width: Int, height: Int) {
        guard let first = sps.first, first & 0x9f == 7 else { throw H264Error.missingParameterSets }
        var reader = BitReader(sps, startingAt: 1)
        let profile = UInt8(reader.read(8))
        _ = reader.read(16)
        guard try reader.unsignedExpGolomb() <= 31 else { throw H264Error.invalidSeqParameterSetId(0) }
        var chroma = 1
        var separate = false
        if highProfiles.contains(profile) {
            chroma = try reader.unsignedExpGolomb()
            guard chroma <= 3 else { throw H264Error.invalidChromaFormat(chroma) }
            if chroma == 3 { separate = reader.flag() }
            guard try reader.unsignedExpGolomb() <= 6, try reader.unsignedExpGolomb() <= 6 else {
                throw H264Error.unsupportedBitDepth
            }
            _ = reader.read(1)
            if reader.flag() {
                let counts = chroma == 3 ? 12 : 8
                for scale in 0..<counts {
                    guard reader.flag() else { continue }
                    var last = 8
                    var next = 8
                    for _ in 0..<(scale < 6 ? 16 : 64) {
                        if next != 0 {
                            next = ((last + (try reader.signedExpGolomb())) % 256 + 256) % 256
                            if next != 0 { last = next }
                        }
                    }
                }
            }
        }
        guard try reader.unsignedExpGolomb() <= 12 else { throw H264Error.invalidFrameNum(0) }
        switch try reader.unsignedExpGolomb() {
        case 0:
            guard try reader.unsignedExpGolomb() <= 12 else { throw H264Error.invalidFrameNum(1) }
        case 1:
            _ = reader.read(1)
            _ = try reader.signedExpGolomb()
            _ = try reader.signedExpGolomb()
            let cycle = try reader.unsignedExpGolomb()
            guard cycle <= 255 else { throw H264Error.pictureOrderCycleTooLong(cycle) }
            for _ in 0..<cycle { _ = try reader.signedExpGolomb() }
        case 2:
            break
        default:
            throw H264Error.invalidPicOrderCntType(3)
        }
        _ = try reader.unsignedExpGolomb()
        _ = reader.read(1)
        let widthInMbs = try reader.unsignedExpGolomb() + 1
        let heightInMapUnits = try reader.unsignedExpGolomb() + 1
        let frameOnly = reader.flag()
        if !frameOnly { _ = reader.read(1) }
        _ = reader.read(1)
        var crop = [0, 0, 0, 0]
        if reader.flag() {
            for i in 0..<4 { crop[i] = try reader.unsignedExpGolomb() }
        }
        let chromaIdc = separate ? 0 : chroma
        let x = (chromaIdc == 1 || chromaIdc == 2) ? 2 : 1
        let factor = frameOnly ? 1 : 2
        let y = chromaIdc == 1 ? 2 * factor : factor
        let width = widthInMbs * 16 - (crop[0] + crop[1]) * x
        let height = heightInMapUnits * 16 * factor - (crop[2] + crop[3]) * y
        guard width > 0, height > 0 else { throw H264Error.invalidPictureSize(width: width, height: height) }
        return (width, height)
    }
}
